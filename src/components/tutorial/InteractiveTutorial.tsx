type StepAction = "info" | "click";
type StepPlacement = "center" | "top" | "right" | "bottom" | "left";

interface TutorialStep {
  id: string;
  view: ViewName;
  title: string;
  body: string;
  action: StepAction;
  selectors?: string[];
  placement?: StepPlacement;
}

