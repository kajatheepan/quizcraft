function getTarget(step: TutorialStep): HTMLElement | null {
  if (!step.selectors || step.selectors.length === 0) return null;

  for (const selector of step.selectors) {
    const element = document.querySelector(selector) as HTMLElement | null;
    if (!element) continue;
    const rect = element.getBoundingClientRect();
    if (rect.width > 0 && rect.height > 0) return element;
  }

  return null;
}

function clamp(value: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, value));
}

export default function InteractiveTutorial({ currentView }: { currentView: ViewName }) {
  const [open, setOpen] = useState(false);
  const [stepIndex, setStepIndex] = useState(0);
  const [targetRect, setTargetRect] = useState<DOMRect | null>(null);
  const dialogRef = useRef<HTMLDivElement>(null);
  const skipButtonRef = useRef<HTMLButtonElement>(null);
  const previousFocusRef = useRef<HTMLElement | null>(null);

  const step = STEPS[stepIndex];

  const cardStyle = useMemo(() => {
    const width = 330;

    if (!targetRect || (step?.placement ?? "center") === "center") {
      return {
        top: "50%",
        left: "50%",
        transform: "translate(-50%, -50%)",
        width,
      } as const;
    }

    const placement = step?.placement ?? "bottom";
    const margin = 12;

    let top = targetRect.bottom + margin;
    let left = clamp(targetRect.left, 12, window.innerWidth - width - 12);

    if (placement === "top") {
      top = targetRect.top - 180;
      left = clamp(targetRect.left, 12, window.innerWidth - width - 12);
    } else if (placement === "right") {
      top = clamp(targetRect.top, 70, window.innerHeight - 200);
      left = targetRect.right + margin;
      if (left + width > window.innerWidth - 12) {
        left = clamp(targetRect.left - width - margin, 12, window.innerWidth - width - 12);
      }
    } else if (placement === "left") {
      top = clamp(targetRect.top, 70, window.innerHeight - 200);
      left = targetRect.left - width - margin;
      if (left < 12) {
        left = clamp(targetRect.right + margin, 12, window.innerWidth - width - 12);
      }
    }

    top = clamp(top, 70, window.innerHeight - 220);

    return {
      top,
      left,
      width,
    } as const;
  }, [step?.placement, targetRect]);

  const closeTutorial = (markSeen: boolean) => {
    if (markSeen) saveTutorialSeen(true);
    setOpen(false);
    setStepIndex(0);
    setTargetRect(null);
  };

  const nextStep = () => {
    if (stepIndex >= STEPS.length - 1) {
      closeTutorial(true);
      return;
    }
    setStepIndex((current) => current + 1);
  };

  const prevStep = () => {
    setStepIndex((current) => Math.max(0, current - 1));
  };

  useEffect(() => {
    if (!getTutorialSeen()) {
      setOpen(true);
      setStepIndex(0);
    }

    const onStart = () => {
      setOpen(true);
      setStepIndex(0);
    };

    window.addEventListener("start-interactive-tutorial", onStart);
    return () => window.removeEventListener("start-interactive-tutorial", onStart);
  }, []);

  useEffect(() => {
    if (!open || !step) return;

    const refreshTarget = () => {
      const target = getTarget(step);
      setTargetRect(target ? target.getBoundingClientRect() : null);
    };

    refreshTarget();
    window.addEventListener("resize", refreshTarget);
    window.addEventListener("scroll", refreshTarget, true);

    const interval = window.setInterval(refreshTarget, 250);
    return () => {
      window.removeEventListener("resize", refreshTarget);
      window.removeEventListener("scroll", refreshTarget, true);
      window.clearInterval(interval);
    };
  }, [open, stepIndex, step]);

  useEffect(() => {
    if (!open) return;

    previousFocusRef.current = document.activeElement instanceof HTMLElement
      ? document.activeElement
      : null;

    const focusTimer = window.setTimeout(() => {
      skipButtonRef.current?.focus();
    }, 0);

    const handleDialogKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        event.preventDefault();
        closeTutorial(false);
        return;
      }

      if (event.key !== "Tab") return;

      const dialog = dialogRef.current;
      if (!dialog) return;

      const focusable = Array.from(
        dialog.querySelectorAll<HTMLElement>(
          'button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])'
        )
      ).filter((element) => !element.hasAttribute("disabled"));

      if (focusable.length === 0) return;

      const first = focusable[0];
      const last = focusable[focusable.length - 1];

      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault();
        last.focus();
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault();
        first.focus();
      }
    };

    document.addEventListener("keydown", handleDialogKeyDown);
    return () => {
      window.clearTimeout(focusTimer);
      document.removeEventListener("keydown", handleDialogKeyDown);
      previousFocusRef.current?.focus();
      previousFocusRef.current = null;
    };
  }, [open]);

  useEffect(() => {
    if (!open || !step || step.action !== "click") return;

    const onClick = (event: MouseEvent) => {
      if (!step.selectors || step.selectors.length === 0) return;

      const target = event.target as HTMLElement | null;
      if (!target) return;

      const matched = step.selectors.some((selector) => target.closest(selector));
      if (matched) {
        window.setTimeout(() => nextStep(), 120);
      }
    };

    document.addEventListener("click", onClick, true);
    return () => document.removeEventListener("click", onClick, true);
  }, [open, stepIndex, step]);

  if (!open || !step) return null;

  const targetMissing = step.action === "click" && (!targetRect || currentView !== step.view);
  const titleId = `tutorial-title-${step.id}`;
  const bodyId = `tutorial-body-${step.id}`;

  return (
    <div className="fixed inset-0 z-[130] pointer-events-none">
      {targetRect && currentView === step.view && (
        <div
          className="pointer-events-none fixed rounded-lg border-2 border-accent/90 shadow-[0_0_0_9999px_rgba(0,0,0,0.45)]"
          style={{
            top: targetRect.top - 6,
            left: targetRect.left - 6,
            width: targetRect.width + 12,
            height: targetRect.height + 12,
          }}
        />
      )}

      <div
        ref={dialogRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby={titleId}
        aria-describedby={bodyId}
        className="fixed pointer-events-auto bg-surface border border-border rounded-xl shadow-card p-4"
        style={cardStyle}
      >
        <p className="text-2xs font-medium tracking-[0.1em] uppercase text-accent mb-1">
          Interactive Tutorial
        </p>
        <h3 id={titleId} className="text-base font-semibold text-primary mb-2">{step.title}</h3>
        <p id={bodyId} className="text-sm text-secondary leading-relaxed whitespace-pre-line mb-4">{step.body}</p>

        {targetMissing && step.action === "click" && (
          <p className="text-xs text-secondary mb-4">
            Go to the {step.view} section and complete the highlighted task.
          </p>
        )}

        <div className="flex items-center justify-between gap-3">
          <button
            ref={skipButtonRef}
            type="button"
            onClick={() => closeTutorial(true)}
            className="rounded-sm text-xs text-secondary hover:text-primary transition-colors duration-[150ms] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
          >
            Skip tutorial
          </button>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={prevStep}
              disabled={stepIndex === 0}
              className="px-3 py-1.5 rounded-md border border-border text-xs text-secondary hover:text-primary transition-colors duration-[150ms] disabled:opacity-40 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
            >
              Back
            </button>
            {step.action === "info" && (
              <button
                type="button"
                onClick={nextStep}
                className="px-4 py-1.5 rounded-md bg-accent text-white text-xs font-medium hover:opacity-90 transition-opacity duration-[150ms] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent focus-visible:ring-offset-2 focus-visible:ring-offset-bg"
              >
                Continue
              </button>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
