"use client";

// First-run onboarding modal. This replaces the older step-by-step coach
// tutorial because the app only needs to explain the AI quiz workflow once.
// Now redesigned to be a stunning premium 3-slide interactive carousel.

import { useEffect, useRef, useState } from "react";
import Image from "next/image";
import { useAppStore } from "@/store/useAppStore";
import { Sparkles, Brain, Share2, Play, ChevronLeft, ChevronRight, X } from "lucide-react";

const ONBOARDING_KEY = "quizcraft_onboarding_seen";

function getOnboardingSeen(): boolean {
  if (typeof window === "undefined") return true;
  return window.localStorage.getItem(ONBOARDING_KEY) === "true";
}

function saveOnboardingSeen(): void {
  window.localStorage.setItem(ONBOARDING_KEY, "true");
}

export default function InteractiveTutorial() {
  const { navigate } = useAppStore();
  const [open, setOpen] = useState(false);
  const [slide, setSlide] = useState(0);
  const [dontShowAgain, setDontShowAgain] = useState(true);
  const dialogRef = useRef<HTMLDivElement>(null);
  const primaryRef = useRef<HTMLButtonElement>(null);
  const previousFocusRef = useRef<HTMLElement | null>(null);

  const closeModal = (persist = dontShowAgain) => {
    if (persist) saveOnboardingSeen();
    setOpen(false);
  };

  const goTo = (view: "input" | "prompt") => {
    saveOnboardingSeen();
    setOpen(false);
    navigate(view);
  };

  useEffect(() => {
    if (!getOnboardingSeen()) {
      setOpen(true);
    }

    const onStart = () => {
      setDontShowAgain(false);
      setSlide(0);
      setOpen(true);
    };

    window.addEventListener("start-interactive-tutorial", onStart);
    return () => window.removeEventListener("start-interactive-tutorial", onStart);
  }, []);

  useEffect(() => {
    if (!open) return;

    previousFocusRef.current = document.activeElement instanceof HTMLElement
      ? document.activeElement
      : null;

    const focusTimer = window.setTimeout(() => {
      if (slide === 2) {
        primaryRef.current?.focus();
      }
    }, 0);

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        event.preventDefault();
        closeModal();
        return;
      }

      if (event.key !== "Tab") return;

      const dialog = dialogRef.current;
      if (!dialog) return;

      const focusable = Array.from(
        dialog.querySelectorAll<HTMLElement>(
          'button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])'
        )
      ).filter((element) => !element.hasAttribute("disabled"));

      if (focusable.length === 0) return;

      const first = focusable[0];
      const last = focusable[focusable.length - 1];

      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault();
        last.focus();
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault();
        first.focus();
      }
    };

    document.addEventListener("keydown", handleKeyDown);
    return () => {
      window.clearTimeout(focusTimer);
      document.removeEventListener("keydown", handleKeyDown);
      previousFocusRef.current?.focus();
      previousFocusRef.current = null;
    };
  }, [open, dontShowAgain, slide]);

  if (!open) return null;

  const slides = [
    {
      badge: "Paste & Practice",
      title: "Transform Study Notes Instantly",
      description: "Paste raw questions generated by ChatGPT, Claude, or your own lecture notes. QuizCraft Plus formats and renders them in seconds—with no configuration or logins required.",
      visual: (
        <div className="rounded-xl border border-border/60 bg-bg/50 p-5 font-mono text-[11px] leading-relaxed text-secondary/90 shadow-inner h-full flex flex-col justify-center">
          <div className="flex items-center gap-1.5 border-b border-border/40 pb-2 mb-3 text-2xs text-secondary/70">
            <span className="h-2 w-2 rounded-full bg-accent animate-ping" />
            <span>AI Parser Input Template</span>
          </div>
          <div className="space-y-1">
            <p className="text-primary font-medium">1. What is transport layer routing?</p>
            <p>A. Identifying physical network cables</p>
            <p className="text-accent font-semibold">B. End-to-end communication via port numbers</p>
            <p>C. Choosing optimal wide-area routes</p>
            <p className="text-success font-semibold mt-1">Answer: B</p>
          </div>
        </div>
      ),
    },
    {
      badge: "Robust Study Engine",
      title: "Interactive Practice Formats",
      description: "Engage your memory with multiple interactive formats. Practice with Multiple Choice Questions, Fill-in-the-blanks, drag-and-drop choices, and True/False toggles, all tracked by responsive timers.",
      visual: (
        <div className="rounded-xl border border-border/60 bg-bg/50 p-5 font-sans text-xs shadow-inner h-full flex flex-col justify-center">
          <div className="flex items-center justify-between border-b border-border/40 pb-2 mb-4">
            <span className="text-secondary font-medium">Question 5 of 20</span>
            <span className="font-mono text-error font-semibold bg-error/10 px-2 py-0.5 rounded border border-error/20 pulse-glow">09:42</span>
          </div>
          <p className="font-semibold text-primary mb-3">Which protocol ensures reliable delivery?</p>
          <div className="space-y-2.5">
            <div className="flex items-center gap-2.5 px-3 py-2 border border-success bg-success/5 rounded-md text-success font-medium">
              <span className="w-5 h-5 rounded-full bg-success text-bg flex items-center justify-center font-bold text-[10px]">✓</span>
              <span>TCP (Reliable)</span>
            </div>
            <div className="flex items-center gap-2.5 px-3 py-2 border border-border bg-bg/30 rounded-md opacity-60">
              <span className="w-5 h-5 rounded-full bg-border flex items-center justify-center font-mono text-[10px]">B</span>
              <span>UDP (Unreliable)</span>
            </div>
          </div>
        </div>
      ),
    },
    {
      badge: "Collaborative Learning",
      title: "Zero-Signups Quiz Sharing",
      description: "Click \"Share Quiz\" to package your active study session into a single compressed link. Friends and classmates can launch the exact same interactive practice dashboard instantly with zero account setup.",
      visual: (
        <div className="rounded-xl border border-border/60 bg-bg/50 p-5 font-sans text-xs shadow-inner h-full flex flex-col justify-center">
          <div className="flex items-center gap-2 border-b border-border/40 pb-2 mb-4 text-secondary font-medium">
            <Share2 className="h-4 w-4 text-accent animate-pulse" />
            <span>Compiled Sharing Link</span>
          </div>
          <div className="p-3.5 rounded-lg bg-bg border border-border/40 flex items-center justify-between gap-3 shadow-sm">
            <span className="font-mono text-accent truncate select-all">quizcraft.plus/share/8hF3k2m...</span>
            <span className="text-2xs font-semibold uppercase tracking-wider text-success px-2 py-0.5 rounded-full bg-success/15 border border-success/30">
              Copied!
            </span>
          </div>
          <p className="mt-4 text-2xs text-secondary/80 leading-relaxed text-center">
            One-tap URL packaging links study buddies instantly to practice and review.
          </p>
        </div>
      ),
    },
  ];

  const current = slides[slide];

  return (
    <div
      className="fixed inset-0 z-[130] flex items-center justify-center bg-black/70 backdrop-blur-md px-4 py-6 animate-fade-in"
      onMouseDown={(event) => {
        if (event.target === event.currentTarget) closeModal();
      }}
    >
      <div
        ref={dialogRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby="onboarding-title"
        aria-describedby="onboarding-description"
        className="relative w-[min(820px,94vw)] max-h-[90vh] overflow-y-auto rounded-2xl border border-border/80 bg-surface/95 backdrop-blur-lg p-6 shadow-card-lg animate-fade-in sm:p-8 flex flex-col"
      >
        <button
          type="button"
          onClick={() => closeModal()}
          aria-label="Close onboarding"
          className="absolute right-5 top-5 flex h-8 w-8 items-center justify-center rounded-full border border-border text-secondary transition-colors duration-[150ms] hover:border-secondary hover:text-primary focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
        >
          <X className="h-4 w-4" />
        </button>

        {/* Brand Header */}
        <div className="mb-6 flex items-center gap-3">
          <Image
            src="/logo.webp"
            alt=""
            width={32}
            height={32}
            className="h-8 w-8 rounded-lg shadow-md"
            aria-hidden="true"
          />
          <h1 className="text-sm font-semibold tracking-wider text-secondary uppercase">
            QuizCraft Plus
          </h1>
        </div>

        {/* Responsive Content Grid */}
        <div className="grid gap-6 md:grid-cols-2 md:items-center flex-grow min-h-[260px]">
          {/* Text Section */}
          <div className="flex flex-col justify-center h-full pr-2">
            <span className="self-start inline-flex items-center rounded-full border border-accent/30 bg-accent/15 px-2.5 py-0.5 text-2xs font-bold uppercase tracking-wider text-accent mb-3 animate-pulse">
              ✦ {current.badge}
            </span>
            <h2 id="onboarding-title" className="text-2xl font-bold tracking-tight leading-tight text-primary sm:text-3xl">
              {current.title}
            </h2>
            <p id="onboarding-description" className="mt-3.5 text-sm leading-relaxed text-secondary/95">
              {current.description}
            </p>

            {/* Slide Action / CTA Area */}
            <div className="mt-6">
              {slide === 2 ? (
                <div className="flex flex-col gap-3.5">
                  <div className="flex flex-wrap gap-2.5">
                    <button
                      ref={primaryRef}
                      type="button"
                      onClick={() => goTo("input")}
                      className="btn-anim inline-flex items-center justify-center gap-2 rounded-lg bg-accent px-5 py-2.5 text-sm font-semibold text-white shadow-md shadow-accent/15 hover:opacity-95 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent focus-visible:ring-offset-2 focus-visible:ring-offset-bg"
                    >
                      <Play className="h-4 w-4 stroke-[2.5px]" />
                      Paste a Quiz
                    </button>
                    <button
                      type="button"
                      onClick={() => goTo("prompt")}
                      className="btn-anim inline-flex items-center justify-center gap-2 rounded-lg border border-border bg-bg/50 px-5 py-2.5 text-sm font-semibold text-primary hover:border-secondary hover:bg-bg/85 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
                    >
                      <Sparkles className="h-4 w-4" />
                      Generate with AI
                    </button>
                  </div>
                  
                  <label className="flex items-center gap-2 text-xs text-secondary cursor-pointer select-none hover:text-primary transition-colors">
                    <input
                      type="checkbox"
                      checked={dontShowAgain}
                      onChange={(event) => setDontShowAgain(event.target.checked)}
                      className="h-4 w-4 accent-[hsl(var(--color-accent))] rounded border-border/60 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
                    />
                    Don&apos;t show this onboarding again
                  </label>
                </div>
              ) : (
                <button
                  type="button"
                  onClick={() => setSlide((s) => s + 1)}
                  className="btn-anim inline-flex items-center justify-center gap-1.5 rounded-lg bg-accent px-5 py-2.5 text-sm font-semibold text-white shadow-md shadow-accent/15 hover:opacity-95 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
                >
                  <span>Continue</span>
                  <ChevronRight className="h-4 w-4" />
                </button>
              )}
            </div>
          </div>

          {/* Visual Showcase Section */}
          <div className="h-full min-h-[200px] flex flex-col justify-center">
            {current.visual}
          </div>
        </div>

        {/* Carousel Footer Navigation */}
        <div className="mt-8 pt-4 border-t border-border/40 flex items-center justify-between">
          {/* Back Button */}
          <button
            type="button"
            disabled={slide === 0}
            onClick={() => setSlide((s) => s - 1)}
            className="inline-flex items-center gap-1 text-sm text-secondary hover:text-primary transition-colors disabled:opacity-30 disabled:hover:text-secondary focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent rounded px-2 py-1"
          >
            <ChevronLeft className="h-4 w-4" />
            <span>Back</span>
          </button>

          {/* Dots Indicator */}
          <div className="flex gap-2">
            {slides.map((_, i) => (
              <button
                key={i}
                type="button"
                onClick={() => setSlide(i)}
                className={`h-2 rounded-full transition-all duration-300 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent ${
                  slide === i ? "w-6 bg-accent" : "w-2 bg-border hover:bg-secondary/60"
                }`}
                aria-label={`Go to slide ${i + 1}`}
                aria-current={slide === i ? "true" : undefined}
              />
            ))}
          </div>

          {/* Skip / Close Button */}
          <button
            type="button"
            onClick={() => closeModal()}
            className="text-sm text-secondary hover:text-primary transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent rounded px-2 py-1"
          >
            {slide === 2 ? "Close" : "Skip for now"}
          </button>
        </div>
      </div>
    </div>
  );
}
